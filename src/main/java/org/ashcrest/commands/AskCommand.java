package org.ashcrest.commands;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.ashcrest.core.Config;
import net.dv8tion.jda.api.EmbedBuilder;
import net.dv8tion.jda.api.events.interaction.command.SlashCommandInteractionEvent;
import net.dv8tion.jda.api.events.message.MessageReceivedEvent;
import net.dv8tion.jda.api.interactions.commands.OptionMapping;
import okhttp3.*;

import java.awt.Color;
import java.io.IOException;
import java.util.concurrent.Executors;


public class AskCommand implements ICommand {
    private static final OkHttpClient httpClient = new OkHttpClient.Builder()
            .connectTimeout(30, java.util.concurrent.TimeUnit.SECONDS)
            .readTimeout(60, java.util.concurrent.TimeUnit.SECONDS)
            .writeTimeout(60, java.util.concurrent.TimeUnit.SECONDS)
            .build();
    private static final ObjectMapper objectMapper = new ObjectMapper();

    @Override
    public void execute(MessageReceivedEvent event, String[] args) {
        if (args.length == 0) {
            event.getChannel().sendMessage("⚠️ Usage: `!ask <your question or prompt>`").queue();
            return;
        }

        String prompt = String.join(" ", args);
        Executors.newVirtualThreadPerTaskExecutor().submit(() -> {
            String answer = queryGemini(prompt);
            sendEmbedReply(event.getChannel().asTextChannel(), prompt, answer);
        });
    }

    @Override
    public void execute(SlashCommandInteractionEvent event) {
        event.deferReply().queue();

        OptionMapping option = event.getOption("prompt");
        if (option == null) {
            event.getHook().sendMessage("⚠️ Please provide a prompt or question.").queue();
            return;
        }

        String prompt = option.getAsString();
        Executors.newVirtualThreadPerTaskExecutor().submit(() -> {
            String answer = queryGemini(prompt);
            sendSlashEmbedReply(event, prompt, answer);
        });
    }

    private String queryGemini(String prompt) {
        String apiKey = Config.GEMINI_API_KEY;
        if (apiKey == null || apiKey.trim().isEmpty()) {
            return "⚠️ **Gemini API key is missing.** Please configure `GEMINI_API_KEY` in your `.env` file to enable AI answers.";
        }

        try {
            String jsonPayload = objectMapper.writeValueAsString(new GeminiRequest(prompt));
            RequestBody body = RequestBody.create(jsonPayload, MediaType.parse("application/json; charset=utf-8"));

            String url = Config.GEMINI_API_URL + "?key=" + apiKey;
            Request request = new Request.Builder()
                    .url(url)
                    .post(body)
                    .build();

            try (Response response = httpClient.newCall(request).execute()) {
                if (!response.isSuccessful()) {
                    String errBody = response.body() != null ? response.body().string() : "";
                    return "❌ Gemini API error (HTTP " + response.code() + "): " + extractErrorMessage(errBody);
                }

                if (response.body() == null) {
                    return "❌ Empty response received from Gemini API.";
                }

                JsonNode root = objectMapper.readTree(response.body().string());
                JsonNode candidates = root.path("candidates");
                if (candidates.isArray() && !candidates.isEmpty()) {
                    JsonNode textNode = candidates.get(0).path("content").path("parts").get(0).path("text");
                    if (!textNode.isMissingNode()) {
                        return textNode.asText();
                    }
                }
                return "⚠️ No response generated by Gemini AI for this prompt.";
            }
        } catch (Exception e) {
            return "❌ Error communicating with Gemini AI: " + e.getMessage();
        }
    }

    private String extractErrorMessage(String jsonErr) {
        try {
            JsonNode root = objectMapper.readTree(jsonErr);
            JsonNode msg = root.path("error").path("message");
            if (!msg.isMissingNode()) {
                return msg.asText();
            }
        } catch (IOException ignored) {}
        return "Failed to process AI request.";
    }

    private void sendSlashEmbedReply(SlashCommandInteractionEvent event, String prompt, String answer) {
        String prefix = "✨ **Aegis AI Assistant**\n\n**❓ Prompt:** `" + prompt + "`\n\n";
        org.ashcrest.core.MessageUtils.sendLongMessageSlash(event, prefix, answer);
    }

    private void sendEmbedReply(net.dv8tion.jda.api.entities.channel.concrete.TextChannel channel, String prompt, String answer) {
        String prefix = "✨ **Aegis AI Assistant**\n\n**❓ Prompt:** `" + prompt + "`\n\n";
        org.ashcrest.core.MessageUtils.sendLongMessage(channel, prefix, answer);
    }

    @Override
    public String getName() { return "ask"; }

    @Override
    public String getDescription() { return "Ask Aegis AI (powered by Google Gemini 3.6 Flash)"; }

    @Override
    public String getUsage() { return "!ask <question | prompt>"; }


    private record GeminiRequest(java.util.List<Content> contents) {
        public GeminiRequest(String text) {
            this(java.util.List.of(new Content(java.util.List.of(new Part(text)))));
        }
        private record Content(java.util.List<Part> parts) {}
        private record Part(String text) {}
    }
}
