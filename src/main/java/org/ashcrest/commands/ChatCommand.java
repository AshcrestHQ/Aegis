package org.ashcrest.commands;

import com.fasterxml.jackson.databind.JsonNode;
import com.fasterxml.jackson.databind.ObjectMapper;
import org.ashcrest.core.Config;
import net.dv8tion.jda.api.EmbedBuilder;
import net.dv8tion.jda.api.events.interaction.command.SlashCommandInteractionEvent;
import net.dv8tion.jda.api.events.message.MessageReceivedEvent;
import net.dv8tion.jda.api.interactions.commands.OptionMapping;
import okhttp3.*;

import java.awt.Color;
import java.time.Instant;
import java.util.*;
import java.util.concurrent.ConcurrentHashMap;
import java.util.concurrent.Executors;

/**
 * Stateful Multi-Turn AI Chat Command powered by Google Gemini 3.6 Flash.
 */
public class ChatCommand implements ICommand {
    private static final OkHttpClient httpClient = new OkHttpClient();
    private static final ObjectMapper objectMapper = new ObjectMapper();
    private static final Map<Long, List<Map<String, Object>>> channelHistories = new ConcurrentHashMap<>();

    @Override
    public void execute(MessageReceivedEvent event, String[] args) {
        if (args.length == 0) {
            event.getChannel().sendMessage("⚠️ Usage: `!chat <your message>`").queue();
            return;
        }

        String message = String.join(" ", args);
        long channelId = event.getChannel().getIdLong();

        Executors.newVirtualThreadPerTaskExecutor().submit(() -> {
            String answer = queryGeminiMultiTurn(channelId, message);
            sendEmbedReply(event.getChannel().asTextChannel(), message, answer);
        });
    }

    @Override
    public void execute(SlashCommandInteractionEvent event) {
        event.deferReply().queue();
        OptionMapping opt = event.getOption("message");
        if (opt == null) {
            event.getHook().sendMessage("⚠️ Please provide a message.").queue();
            return;
        }

        String message = opt.getAsString();
        long channelId = event.getChannel().getIdLong();

        Executors.newVirtualThreadPerTaskExecutor().submit(() -> {
            String answer = queryGeminiMultiTurn(channelId, message);
            sendSlashEmbedReply(event, message, answer);
        });
    }

    private String queryGeminiMultiTurn(long channelId, String userMessage) {
        String apiKey = Config.GEMINI_API_KEY;
        if (apiKey == null || apiKey.trim().isEmpty()) {
            return "⚠️ **Gemini API key is missing.** Please configure `GEMINI_API_KEY` in your `.env` file.";
        }

        List<Map<String, Object>> history = channelHistories.computeIfAbsent(channelId, k -> Collections.synchronizedList(new ArrayList<>()));

        // Add user message
        Map<String, Object> userContent = Map.of("role", "user", "parts", List.of(Map.of("text", userMessage)));
        history.add(userContent);

        // Keep sliding window of last 10 messages
        while (history.size() > 10) {
            history.remove(0);
        }

        try {
            Map<String, Object> payloadMap = Map.of("contents", new ArrayList<>(history));
            String jsonPayload = objectMapper.writeValueAsString(payloadMap);
            RequestBody body = RequestBody.create(jsonPayload, MediaType.parse("application/json; charset=utf-8"));

            String url = Config.GEMINI_API_URL + "?key=" + apiKey;
            Request request = new Request.Builder().url(url).post(body).build();

            try (Response response = httpClient.newCall(request).execute()) {
                if (!response.isSuccessful()) {
                    return "❌ Gemini API Error (HTTP " + response.code() + ")";
                }

                if (response.body() == null) return "❌ Empty response received.";

                JsonNode root = objectMapper.readTree(response.body().string());
                JsonNode candidates = root.path("candidates");
                if (candidates.isArray() && !candidates.isEmpty()) {
                    JsonNode textNode = candidates.get(0).path("content").path("parts").get(0).path("text");
                    if (!textNode.isMissingNode()) {
                        String botAnswer = textNode.asText();
                        Map<String, Object> modelContent = Map.of("role", "model", "parts", List.of(Map.of("text", botAnswer)));
                        history.add(modelContent);
                        return botAnswer;
                    }
                }
                return "⚠️ No reply generated by Gemini AI.";
            }
        } catch (Exception e) {
            return "❌ AI Chat Error: " + e.getMessage();
        }
    }

    private void sendEmbedReply(net.dv8tion.jda.api.entities.channel.concrete.TextChannel channel, String prompt, String answer) {
        EmbedBuilder embed = new EmbedBuilder()
                .setTitle("🤖 Aegis Stateful AI Chat")
                .setColor(new Color(0x7289DA))
                .addField("💬 Prompt", prompt.length() > 250 ? prompt.substring(0, 247) + "..." : prompt, false)
                .setDescription(answer.length() > 3900 ? answer.substring(0, 3897) + "..." : answer)
                .setFooter("Powered by Google Gemini 3.6 Flash | Channel Context Enabled", null)
                .setTimestamp(Instant.now());

        channel.sendMessageEmbeds(embed.build()).queue();
    }

    private void sendSlashEmbedReply(SlashCommandInteractionEvent event, String prompt, String answer) {
        EmbedBuilder embed = new EmbedBuilder()
                .setTitle("🤖 Aegis Stateful AI Chat")
                .setColor(new Color(0x7289DA))
                .addField("💬 Prompt", prompt.length() > 250 ? prompt.substring(0, 247) + "..." : prompt, false)
                .setDescription(answer.length() > 3900 ? answer.substring(0, 3897) + "..." : answer)
                .setFooter("Powered by Google Gemini 3.6 Flash | Channel Context Enabled", null)
                .setTimestamp(Instant.now());

        event.getHook().sendMessageEmbeds(embed.build()).queue();
    }

    @Override
    public String getName() { return "chat"; }

    @Override
    public String getDescription() { return "Stateful multi-turn AI conversation maintaining channel context via Gemini 3.6 Flash"; }

    @Override
    public String getUsage() { return "!chat <message> or /chat message:<text>"; }
}
